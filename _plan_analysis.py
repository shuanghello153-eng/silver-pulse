# 大标签当前数量
all_l2 = Counter()
for e in d:
    for t in e.get("tag_l2", []):
        all_l2[t] += 1

idx = { (e.get("name_cn") or e.get("name")): e for e in d }

lines = []
for tag, buckets in THEMES.items():
    members = [e for e in d if tag in e.get("tag_l2", [])]
    total = len(members)
    counts = Counter()
    unmatched = []
    for e in members:
        nm = e.get("name_cn") or e.get("name")
        tx = desc_of(e)
        placed = False
        for bname, kws in buckets:
            if any(k in tx for k in kws):
                counts[bname] += 1
                placed = True
                break
        if not placed:
            unmatched.append(nm)
    lines.append(f"## {tag} (当前 {total})")
    for bname, kws in buckets:
        lines.append(f"  - {bname}: {counts[bname]}  (命中词: {','.join(kws[:4])})")
    lines.append(f"  - [未匹配/残留]: {len(unmatched)}")
    if unmatched:
        lines.append(f"    残留样例: {', '.join(unmatched[:8])}")
    lines.append("")

out = "\n".join(lines)
print(out)
