def ser(e):
    return str(e.get("serial", "")).lstrip("#")

d = json.load(open(DB, encoding="utf-8"))
by = {ser(e): e for e in d}
batch = json.load(open(os.path.join(HERE, "batches_full", "batch_src_006.json"), encoding="utf-8"))

recs = list(RECOMMENDS.values())
fails = {}
for item in batch:
    s = item["serial"]
    e = by.get(s.lstrip("#"))
    if not e:
        fails[s] = ["serial不在DB"]
        continue
    tmp = dict(e)
    tmp["recommend"] = RECOMMENDS[s]
    iss = validate(tmp, others=recs)
    if iss:
        fails[s] = iss

print(f"校验 {len(batch)} 家 | 通过 {len(batch)-len(fails)} | 未过 {len(fails)}")
for s, iss in fails.items():
    print(f"  {s}: {iss}")

if not fails:
    for s in RECOMMENDS:
        fp = os.path.join(HERE, "drafts_v4", f"draft_{s}.json")
        json.dump({"serial": s, "recommend": RECOMMENDS[s]},
                  open(fp, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    print("全部 PASS，已写入 drafts_v4/")
else:
    print("存在 FAIL，未写入。")
