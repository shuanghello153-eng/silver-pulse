    s = e["serial"]
    if s not in REC:
        failed.append((s, ["缺少recommend"]))
        continue
    rec = REC[s]
    ctx = {
        "recommend": rec,
        "name": e.get("name", ""),
        "name_cn": e.get("name_cn", ""),
        "stage": e.get("stage", ""),
        "desc_cn": e.get("desc_cn", ""),
        "highlights": e.get("highlights", []),
        "funding_latest": e.get("funding_latest", {}),
        "funding_total": e.get("funding_total", {}),
    }
    iss = C.validate(ctx, others=None, skip={"R6", "R7", "R8"})
    if iss:
        failed.append((s, iss))
    else:
        passed.append(s)
        out = {"serial": s, "recommend": rec}
        with open(os.path.join(OUTDIR, f"draft_{s}.json"), "w", encoding="utf-8") as f:
            json.dump(out, f, ensure_ascii=False, indent=2)

