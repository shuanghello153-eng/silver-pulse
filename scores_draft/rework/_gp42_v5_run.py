results = []
for e in batch:
    s = e["serial"]
    if e.get("_is_v5_already"):
        rec = e["current_recommend"]
        # 补整数分：沿用既有 current_* 取整，保证 0~10
        info = int(round(float(e.get("current_info", 6))))
        diff = int(round(float(e.get("current_diff", 6))))
        copy = int(round(float(e.get("current_copy", 6))))
        mode = "KEEP"
    else:
        rec, info, diff, copy = REWRITE[s]
        mode = "REWRITE"
    doc = {
        "serial": s,
        "recommend": rec,
        "info": info,
        "diff": diff,
        "copy": copy,
    }
    fp = os.path.join(OUT, f"draft_{s}.json")
    json.dump(doc, open(fp, "w", encoding="utf-8"), ensure_ascii=False, indent=2)
    p = subprocess.run([sys.executable, os.path.join(HERE, "check_single.py"), fp],
                       capture_output=True, text=True)
    gate = p.stdout.strip()
    results.append((s, mode, info, diff, copy, len(rec), gate))

