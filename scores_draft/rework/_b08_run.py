written = []
fails = []
for it in batch:
    ser = str(it['serial']).lstrip('#')
    if ser in REWRITE:
        rec, info, diff, copy = REWRITE[ser]
        mode = 'REWRITE'
    else:
        rec = it['current_recommend']
        info, diff, copy = score_kept(rec)
        mode = 'KEEP'
    # 写出带 # 文件
    out = {"serial": "#" + ser, "recommend": rec,
            "info_score": int(info), "diff_score": int(diff), "copy_score": int(copy)}
    fp = os.path.join(OUT, "draft_#%s.json" % ser)
    json.dump(out, open(fp, 'w', encoding='utf-8'), ensure_ascii=False, indent=0)
    written.append((ser, mode, rec, info, diff, copy))

