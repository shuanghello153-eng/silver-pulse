# ---- 打分函数（与文本自洽） ----
def has_any(t, keys):
    return any(k in t for k in keys)

INFO_HIGH = ['素材可挖', '案例可挖', '素材够写']           # 触发 info>=7
INFO_STRONG = ['财报', '披露完整', '年报', '招股', '详实', '数据详实']
INFO_SOFT = list(DIM_INFO)
DIFF_TRIG = ['差异在', '壁垒', '卡位', '错位', '罕见', '少见', '反共识', '反常识', '独特', '稀缺', '唯一', '飞轮', '护城河']
DIFF_SOFT = list(DIM_DIFF)
COPY_TRIG = ['可借鉴', '对标', '可学', '可复制', '可平移', '可搬', '可复用', '可参考', '国内可', '学其', '借鉴其', '参考其', '搬其', '复用其']
COPY_ALL = list(DIM_COPY)

def score_kept(t):
    # info
    if has_any(t, INFO_HIGH) or has_any(t, INFO_STRONG):
        info = 8
    elif has_any(t, INFO_SOFT):
        info = 6
    else:
        info = 5
    # diff
    if has_any(t, DIFF_TRIG):
        diff = 7
    elif has_any(t, DIFF_SOFT):
        diff = 6
    else:
        diff = 5
    # copy
    if has_any(t, COPY_TRIG):
        copy = 8
    elif has_any(t, COPY_ALL):
        copy = 7
    else:
        copy = 6
    return info, diff, copy

