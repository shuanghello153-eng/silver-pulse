records = json.load(open(BATCH, encoding="utf-8"))
by_serial = {r["serial"]: r for r in records}

results = []
passed = 0
written = 0
os.makedirs(OUT, exist_ok=True)

for serial, text in RECOMMEND.items():
    rec = by_serial.get(serial)
    if not rec:
        results.append((serial, ["ERR:源文件无此serial"]))
        continue
    # 合并源文件上下文，模拟真实门禁（含 name_cn/stage/desc_cn/highlights/funding_*）
    ctx = {
        "serial": serial,
        "name_cn": rec.get("name_cn", ""),
        "name": rec.get("name", ""),
        "stage": rec.get("stage", ""),
        "desc_cn": rec.get("desc_cn", ""),
        "highlights": rec.get("highlights", []),
        "funding_latest": rec.get("funding_latest", ""),
        "funding_total": rec.get("funding_total", ""),
        "recommend": text,
    }
    issues = C.validate(ctx, others=None, skip={"R6", "R7", "R8"})
    if issues:
        results.append((serial, issues))
        continue
    passed += 1
    # 只写最小格式 {"serial","recommend"}
    out_path = os.path.join(OUT, f"draft_{serial}.json")
    json.dump({"serial": serial, "recommend": text}, open(out_path, "w", encoding="utf-8"), ensure_ascii=False, indent=2)
    written += 1
    results.append((serial, []))

print(f"源文件企业数: {len(by_serial)} | 已撰写: {len(RECOMMEND)} | 通过门禁: {passed} | 写入drafts_v5: {written}")
print("未过门禁的 serial:")
for serial, iss in results:
    if iss:
        print(f"  {serial}: {iss}")
print("疑似非银发 serial:", SUSPECT)
