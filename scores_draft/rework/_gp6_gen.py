data = json.load(open(SRC, encoding="utf-8"))
by_serial = {e["serial"]: e for e in data}

passed = 0
written = 0
fails = []
for serial, rec in RECS.items():
    e = by_serial.get(serial)
    if not e:
        fails.append((serial, "源文件缺失"))
        continue
    ctx = dict(e)
    ctx["recommend"] = rec
    # ensure required fields present
    for k in ("name_cn","stage","desc_cn","highlights","funding_latest","funding_total"):
        if k not in ctx:
            ctx[k] = "" if k in ("funding_latest","funding_total") else (e.get(k) or "")
    iss = C.validate(ctx, others=None, skip={"R6","R7","R8"})
    if iss:
        fails.append((serial, iss))
    else:
        passed += 1
        fn = os.path.join(OUT, f"draft_{serial}.json")
        json.dump({"serial": serial, "recommend": rec}, open(fn, "w", encoding="utf-8"), ensure_ascii=False, indent=2)
        written += 1

print(f"总 {len(RECS)} | 通过 {passed} | 写入 {written}")
for s, iss in fails:
    print(f"  FAIL {s}: {iss}")
