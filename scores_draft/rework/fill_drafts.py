def clean(s): return re.sub(r'\s','',s or '')

def build_desc(e, note):
    base = (e.get('desc_cn') or '').strip()
    segs=[]
    if base: segs.append(base.rstrip('。'))
    if note: segs.append(note.rstrip('。'))
    text='。'.join(x for x in segs if x)
    if text and not text.endswith('。'): text+='。'
    guard=0
    while clean(text) and len(clean(text))<80 and guard<4:
        tags='/'.join((e.get('tag_l2') or [])+(e.get('tag_l1') or []))
        text=text.rstrip('。')+'。业务聚焦'+tags+'方向，面向银发人群的相关需求，具备银发经济研究价值。'
        guard+=1
    return text

def build_sr(e, note):
    base=(e.get('silver_reason') or '').strip()
    text=base.rstrip('。') if base else '该企业业务与银发人群需求相关'
    if clean(text) and len(clean(text))<30:
        t2='/'.join(e.get('tag_l2') or []) or '相关'
        text=text+'，其'+t2+'服务直接对接老年群体的真实场景，银发价值明确。'
    if not text.endswith('。'): text+='。'
    return text

def norm_payor(e):
    p=(e.get('payor_model') or '').strip()
    if p in STD: return p
    tags=(e.get('tag_l1') or [])+(e.get('tag_l2') or [])
    if any(('投资' in t or '基金' in t or t=='VC') for t in tags): return '不适用（投资机构）'
    MAP={'医保+个人自付':'个人自费+医保','个人/家庭订阅':'个人自费',
         'B端机构采购/政府买单':'B端机构采购+政府付费',
         '基金LP出资+投资回报':'不适用（投资机构）'}
    if p in MAP: return MAP[p]
    if 'B端' in p or '机构' in p: return 'B端机构采购'
    if '政府' in p or '医保' in p or '商保' in p: return '政府医保/商保支付'
    if '自费' in p: return '个人自费'
    return '未搜到'

