all_recs = [r for r in RECS.values()]

# build context per serial
pass_cnt = 0
written = []
failed = {}
for serial, rec in RECS.items():
    e = dict(by_serial[serial])
    e["recommend"] = rec
    iss = C.validate(e, others=all_recs, skip={"R6","R7","R8"})
    if iss:
        failed[serial] = iss
        print(f"FAIL {serial}: {iss}")
    else:
        pass_cnt += 1
        outp = os.path.join(OUT, f"draft_{serial}.json")
        json.dump({"serial": serial, "recommend": rec}, open(outp, "w", encoding="utf-8"),
                  ensure_ascii=False, indent=2)
        written.append(serial)

print(f"\n总计 {len(RECS)} | 通过 {pass_cnt} | 写入 {len(written)} | 未过 {len(failed)}")
