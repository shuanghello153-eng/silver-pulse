passed, written, failed = [], [], []
for e in data:
    ser = e["serial"]
    rec = RECS.get(ser)
    if rec is None:
        failed.append((ser, "未写recommend"))
        continue
    ctx = dict(e)
    ctx["recommend"] = rec
    iss = C.validate(ctx, others=None, skip={"R6", "R7", "R8"})
    if iss:
        failed.append((ser, iss))
        continue
    passed.append(ser)
    out = {"serial": ser, "recommend": rec}
    with open(os.path.join(OUTDIR, f"draft_{ser}.json"), "w", encoding="utf-8") as f:
        json.dump(out, f, ensure_ascii=False, indent=2)
    written.append(ser)

