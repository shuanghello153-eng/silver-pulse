def main():
    data = json.load(open(SRC, encoding="utf-8"))
    by_serial = {e["serial"]: e for e in data}
    passed, written, failed = [], [], {}
    for serial, rec in RECOMMENDS.items():
        e = by_serial.get(serial)
        if not e:
            failed[serial] = ["源文件无此 serial"]
            continue
        ctx = dict(e)
        ctx["recommend"] = rec
        iss = C.validate(ctx, others=None, skip={"R6", "R7", "R8"})
        if iss:
            failed[serial] = iss
            continue
        passed.append(serial)
        outp = os.path.join(OUT, f"draft_{serial}.json")
        json.dump({"serial": serial, "recommend": rec},
                  open(outp, "w", encoding="utf-8"), ensure_ascii=False)
        written.append(serial)
    print(f"共 {len(RECOMMENDS)} 家 | 门禁通过 {len(passed)} | 写入 {len(written)} | 未过 {len(failed)}")
    for s, iss in failed.items():
        print(f"  FAIL {s}: {iss}")
    # 字数体检
    for serial, rec in RECOMMENDS.items():
        n = len(rec.replace(" ", ""))
        if n < 50 or n > 240:
            print(f"  LEN {serial}: {n}")

if __name__ == "__main__":
    main()
