skip = {'R6','R7','R8'}
total = len(batch)
passed = 0
written = 0
failed = []
for e in batch:
    serial = e.get("serial")
    rec = RECS.get(serial)
    if rec is None:
        failed.append((serial, ["NO_DRAFT"]))
        continue
    ctx = dict(e)
    ctx["recommend"] = rec
    issues = C.validate(ctx, others=None, skip=skip)
    if issues:
        failed.append((serial, issues))
    else:
        passed += 1
        out = {"serial": serial, "recommend": rec}
        with open(os.path.join(OUTDIR, f"draft_{serial}.json"), "w", encoding="utf-8") as f:
            json.dump(out, f, ensure_ascii=False, indent=2)
        written += 1

