written = 0
for e in batch:
    s = e.get("serial", "")
    name = e.get("name_cn") or e.get("name") or ""
    fp = os.path.join(OUT, f"draft_#{s}.json") if s else None

    if s in AUTH:                       # 0952/1103/1477 全新
        obj = {"serial": s, **AUTH[s]}
    elif s == "":                       # 空 serial
        a = EMPTY_AUTH.get(name)
        if not a:
            print("!! 空serial未匹配:", name); continue
        obj = {"serial": "", **a}
        # 文件名用 EMPTY_<hash(desc)%100000>
        fn = f"draft_#EMPTY_{hash(a['desc_cn'])%100000}.json"
        fp = os.path.join(OUT, fn)
    else:                               # 54 家已有 recommend → 保留
        if not os.path.exists(fp):
            print("!! 缺草稿文件:", s); continue
        d = json.load(open(fp, encoding="utf-8"))
        rec = d.get("recommend")
        if not isinstance(rec, str) or not rec.strip():
            print("!! recommend 空:", s); continue
        ent = db_idx.get(s, {})
