def lcs_sub(a, b):
    import re as _re
    a, b = _re.sub(r"\s", "", a or ""), _re.sub(r"\s", "", b or "")
    if not a or not b:
        return 0, ""
    n, m = len(a), len(b)
    dp = [[0]*(m+1) for _ in range(n+1)]
    end = 0; best = 0
    for i in range(1, n+1):
        for j in range(1, m+1):
            if a[i-1] == b[j-1]:
                dp[i][j] = dp[i-1][j-1] + 1
                if dp[i][j] > best:
                    best = dp[i][j]; end = i
            else:
                dp[i][j] = 0
    return best, a[end-best:end]

