def load_items():
    items = {}
    for b in BATCHES:
        d = json.load(open(os.path.join(HERE, 'batches_full', b), encoding='utf-8'))
        for it in d:
            items[it['serial']] = it
    return items

def cl(s):
    return len(re.sub(r'\s', '', s or ''))

def main():
    items = load_items()
    os.makedirs(OUT, exist_ok=True)
    # R10 跨企业：用已写好的 REC 互相校验
    others = list(REC.values())
    pass_n = 0
    fail_n = 0
    for serial, rec in REC.items():
        it = items.get(serial)
        if not it:
            print('MISSING', serial)
            continue
        # 组装用于校验的上下文（保留全字段，便于 field-dedup）
        ctx = dict(it)
        ctx['recommend'] = rec
        # 应用字段修正
        fx = FIX.get(serial, {})
        if 'desc_cn' in fx:
            ctx['desc_cn'] = fx['desc_cn']
        if 'silver_reason' in fx:
            ctx['silver_reason'] = fx['silver_reason']
        if 'payor_model' in fx:
            ctx['payor_model'] = fx['payor_model']
        issues = validate(ctx, others=others)
        # 写 flag（仅记录，不阻断）
        flag = FLAGS.get(serial, '')
        if fx.get('flag'):
            flag = (flag + '; ' + fx['flag']).strip('; ')
        if issues:
            fail_n += 1
            print(f'FAIL {serial} ({it.get("name")}): {issues}')
        else:
            pass_n += 1
            out = {
                'serial': serial,
                'recommend': rec,
                'desc_cn': ctx['desc_cn'],
                'silver_reason': ctx['silver_reason'],
                'payor_model': ctx['payor_model'],
            }
            if flag:
                out['flag'] = flag
            json.dump(out, open(os.path.join(OUT, f'draft_{serial}.json'), 'w', encoding='utf-8'),
                      ensure_ascii=False, indent=2)
            print(f'PASS {serial} ({it.get("name")}) len={cl(rec)}')
    print(f'\n=== batch008 自校：PASS {pass_n} | FAIL {fail_n} ===')


if __name__ == '__main__':
    main()
