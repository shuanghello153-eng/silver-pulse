src = json.load(open(SRC, encoding="utf-8"))
by_serial = {e["serial"]: e for e in src}

passed, failed, written = [], [], []
for serial, text in recs.items():
    e = by_serial.get(serial)
    if not e:
        failed.append((serial, ["NOT_FOUND"]))
        continue
    ctx = dict(e)
    ctx["recommend"] = text
    # ensure required fields present
    for k in ("name_cn","stage","desc_cn","highlights","funding_latest","funding_total"):
        if k not in ctx:
            ctx[k] = e.get(k, "")
    issues = C.validate(ctx, others=None, skip={"R6","R7","R8"})
    if issues:
        failed.append((serial, issues))
    else:
        passed.append(serial)
        out = {"serial": serial, "recommend": text}
        with open(os.path.join(OUT, f"draft_{serial}.json"), "w", encoding="utf-8") as f:
            json.dump(out, f, ensure_ascii=False, indent=2)
        written.append(serial)

print(f"总数={len(recs)} 通过={len(passed)} 写入={len(written)} 未过={len(failed)}")
for s, iss in failed:
    print(f"  FAIL {s}: {iss}")
