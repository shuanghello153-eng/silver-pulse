DB = os.path.normpath(os.path.join(HERE, "..", "..", "data/enterprise/all_enterprises.json"))
def ctx(serial):
    if not os.path.exists(DB): return {}
    for e in json.load(open(DB, encoding="utf-8")):
        if str(e.get("serial","")).lstrip("#") == serial.lstrip("#"):
            return e
    return {}

fails = []
for serial,(rec,info,diff,copy) in D.items():
    assert 0 <= info <= 10 and 0 <= diff <= 10 and 0 <= copy <= 10
    obj = {"serial": serial, "recommend": rec, "info": info, "diff": diff, "copy": copy}
    fp = os.path.join(OUT, f"draft_{serial}.json")
    json.dump(obj, open(fp, "w", encoding="utf-8"), ensure_ascii=False, indent=2)
    # validate against DB ctx
    tmp = ctx(serial)
    for k in ("recommend","desc_cn","highlights","stage","funding_latest","funding_total"):
        if k in obj and obj[k] is not None:
            tmp[k] = obj[k]
    iss = validate(tmp, skip=["R10","R6","R7","R8"])
    status = "PASS" if not iss else "FAIL:"+str(iss)
    if iss: fails.append((serial, iss))
    print(f"{serial}: {status} (len={len(rec)})")

print(f"\n总计 {len(D)} 条 | 通过 {len(D)-len(fails)} | 未过 {len(fails)}")
