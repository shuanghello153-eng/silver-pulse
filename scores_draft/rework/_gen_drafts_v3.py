sys.stderr.write("AFTER AMT_RE\n"); sys.stderr.flush()

def make_fact(e):
    fl = e.get("funding_latest") or ""
    ft = e.get("funding_total") or ""
    if isinstance(fl, dict):
        fl = fl.get("display") or ""
    if isinstance(ft, dict):
        ft = ft.get("display") or ""
    cand = fl or ft
    if isinstance(cand, str) and re.search(r"\d", cand) and not any(re.search(p, cand) for p in BANNED_RE):
        ym = re.search(r"(\d{4})", cand)
        year = ym.group(1) if ym else ""
        m = AMT_RE.search(cand)
        if m:
            amt = cand[m.start():m.end()].strip()
            fact = (f"{year}年新获融资约{amt}" if year else f"近期新获融资约{amt}")
            return fact
    tags = (e.get("tag_l1") or []) + (e.get("tag_l2") or [])
    tag = tags[0] if tags else "银发"
    return f"这家{tag}企业近期合作与产品落地加速"

