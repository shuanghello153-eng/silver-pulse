for serial, rec in REC.items():
    e = by[serial]
    ctx = {
        "serial": serial,
        "recommend": rec,
        "name": e.get("name", "") or "",
        "name_cn": e.get("name_cn", "") or "",
        "stage": e.get("stage", "") or "",
        "desc_cn": e.get("desc_cn", "") or "",
        "highlights": e.get("highlights", []) or [],
        "funding_latest": e.get("funding_latest", "") or "",
        "funding_total": e.get("funding_total", "") or "",
    }
    iss = C.validate(ctx, others=None, skip={"R6", "R7", "R8"})
    if iss:
        failed.append((serial, iss))
    else:
        passed.append(serial)
        out = {"serial": serial, "recommend": rec}
        with open(os.path.join(OUT, f"draft_{serial}.json"), "w", encoding="utf-8") as f:
            json.dump(out, f, ensure_ascii=False, indent=2)
        written.append(serial)

