# pairwise R10 sanity (warn only)
import itertools
warn = []
for a, b in itertools.combinations(passed, 2):
    if C.lcs_len(REC[a], REC[b]) >= 15:
        sa = set(re.sub(r"\s", "", REC[a])); sb = set(re.sub(r"\s", "", REC[b]))
        if sa and sb and len(sa & sb) / len(sa | sb) > 0.5:
            warn.append((a, b))
if warn:
    print("R10 WARN (pairwise):", warn)
else:
    print("R10 pairwise: OK")
