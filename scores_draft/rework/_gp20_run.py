data = json.load(open(SRC, encoding="utf-8"))
by_serial = {e["serial"]: e for e in data}

passed, failed, written, non_silver = [], [], [], []
# 疑似非银发：desc/highlights 中无 老/银发/养老/适老/康养/认知症/安宁 等老年信号者
SILVER_KW = ["银发", "养老", "适老", "康养", "认知", "安宁", "照护", "老龄化", "长者", "老年", "老人", "护理"]
for serial, text in RECS.items():
    e = by_serial[serial]
    ctx = {**e, "recommend": text}
    issues = C.validate(ctx, others=None, skip={"R6", "R7", "R8"})
    if issues:
        failed.append((serial, issues))
    else:
        passed.append(serial)
        # 写文件
        out = {"serial": serial, "recommend": text}
        with open(os.path.join(OUT, f"draft_{serial}.json"), "w", encoding="utf-8") as f:
            json.dump(out, f, ensure_ascii=False, indent=2)
        written.append(serial)
    # 非银发判定（兼容 highlights 为字符串/列表，并纳入 tag）
    parts = [e.get("desc_cn", "") or ""]
    hl = e.get("highlights")
    if isinstance(hl, str):
        parts.append(hl)
    elif isinstance(hl, list):
        parts.extend([h for h in hl if isinstance(h, str)])
    for tk in ("tag_l1", "tag_l2"):
        v = e.get(tk)
        if isinstance(v, list):
            parts.extend(v)
    blob = " ".join(parts)
    if not any(k in blob for k in SILVER_KW):
        non_silver.append(serial)

print("=== 校验结果 ===")
print(f"总数={len(RECS)} 通过={len(passed)} 写入={len(written)} 未过={len(failed)}")
print("通过:", passed)
if failed:
    print("未过:")
    for s, iss in failed:
        print(f"  {s}: {iss}")
print("疑似非银发 serial (desc/highlights无老年信号):", non_silver)
