# -*- coding: utf-8 -*-
"""生成 200家达标企业的可读审阅 + 评分评价分析思路（markdown，不交JSON）。"""
import json, os
from collections import Counter

HERE = os.path.dirname(os.path.abspath(__file__))
BASE = os.path.normpath(os.path.join(HERE, "..", ".."))
DB = os.path.join(BASE, "data/enterprise/all_enterprises.json")
OUT = os.path.join(HERE, "review200.md")

all200 = ['#0565','#0493','#0855','#1152','#0392','#0783','#0012','#0038','#0557','#0678','#1351','#0398','#0654','#0945','#0561','#0030','#0602','#0478','#0850','#0397','#0810','#0840','#0946','#0009','#0091','#1174','#0227','#0484','#0964','#0593','#0594','#0647','#0683','#0010','#0020','#0938','#0011','#1153','#0969','#0461','#0470','#0949','#0082','#0628','#1168','#1171','#1175','#1178','#1317','#0394','#0725','#0954','#1165','#1177','#0436','#0768','#0907','#0935','#0951','#0952','#1156','#1159','#1169','#1310','#0791','#0466','#0886','#1170','#0732','#0100','#0447','#0477','#0634','#0866','#0885','#1136','#1155','#0034','#0696','#1197','#0401','#0467','#0595','#0950','#0953','#1135','#1145','#1280','#0468','#0475','#0744','#0889','#1158','#1352','#0915','#0558','#0675','#0717','#0966','#1330','#0495','#0560','#0712','#1144','#1166','#0165','#0853','#0978','#0088','#0632','#0646','#1147','#0029','#0471','#0564','#0615','#0718','#0820','#0895','#0993','#1037','#1059','#1114','#1172','#1183','#1184','#1198','#1318','#0849','#0162','#0667','#1160','#1161','#1162','#1163','#1167','#0779','#1320','#0480','#0481','#0974','#1173','#0559','#0959','#0977','#0872','#0169','#0479','#0736','#0017','#0086','#0459','#0652','#0149','#0157','#0757','#0037','#0389','#0639','#0715','#0756','#0804','#0835','#0925','#0170','#0735','#1062','#1063','#1067','#1069','#1115','#1210','#1319','#1326','#0164','#0061','#0089','#0289','#0501','#0727','#0869','#0070','#0129','#0457','#0458','#0464','#0465','#0472','#0482','#0497','#0729','#0741','#0151','#0031','#0032','#0181','#0298','#0456','#0462','#0469']

d = json.load(open(DB, encoding="utf-8"))
by = {e["serial"]: e for e in d}
rows = [by[s] for s in all200 if s in by]
rows.sort(key=lambda e: e.get("research_value", 0), reverse=True)

# ---- 分布统计（用于评分评价分析思路）----
rvs = [e.get("research_value", 0) for e in rows]
def bucket(x):
    if x >= 80: return "80+（强信号标杆）"
    if x >= 70: return "70-79（高价值）"
    if x >= 60: return "60-69（中价值）"
    return "<60（观察池）"
buck = Counter(bucket(x) for x in rvs)
l1 = Counter()
for e in rows:
    for t in (e.get("tag_l1") or []):
        l1[t] += 1

# ---- 写 markdown ----
L = []
L.append("# Silver Pulse 企业库 · 200家高优先企业达标审阅\n")
L.append("> 范围：按 research_value 降序取前 200 家（rv 88.0 → 约 51.6）。\n")
L.append("> 字段含义：推荐理由=帮小爽判断\"写谁/不写谁\"的唯一决策字段，覆盖信号/信息量/差异化/可复制四维度；四维分为另一个AI已算好的客观分（未动）。\n")

# ===== 第一部分：评分评价分析思路 =====
L.append("\n---\n\n## 一、我的评分评价分析思路（怎么判断\"值不值得写\"）\n")
L.append("企业库 1502 家不是都该写。我的判断框架是**四维度交叉**：\n")
L.append("- **信号强度**：现在是不是热点？有没有融资/收购/政策/上线等\"为什么是现在\"的由头。没由头的，除非模式极独特否则不急着写。")
L.append("- **信息量**：公开可查的信息够不够写一篇？财报/用户量/专利/中标等硬数据越足，成文越扎实。")
L.append("- **差异化**：它和别家到底哪不同？没差异=换汤不换药=不写。")
L.append("- **可复制**：对国内创业者有没有借鉴点？纯重资产/纯资本玩法（如跨国药企并购）普通人学不了，就老实判\"参考价值有限\"，不硬吹。\n")
L.append("把四维度落到**选题三型**，帮小爽一眼决策：\n")
L.append("1. **标杆可学型**（如 #0565 橡树街、#0855 Signify）：模式清晰、国内有对照、能提炼方法论 → 优先写。")
L.append("2. **失败警示型**（如 #0493 百思买）：踩坑/止损的故事，对国内跨界者是反面教材 → 高阅读价值。")
L.append("3. **诚实判低型**（如 #0602 Abbvie）：信号与信息极强，但模式不可复制，点明\"看思路别看技术\" → 避免读者误抄。\n")
L.append("**分布（本 200 家）**：" + "；".join(f"{k} {v}家" for k, v in sorted(buck.items(), key=lambda x:-x[1])) + "。\n")
L.append("**一级标签集中度**：" + "、".join(f"{t}{n}" for t, n in l1.most_common()) + "。说明高优先企业集中在养老服务/康复辅具/消费品/投资机构几类，与银发选题主战场吻合。\n")

# ===== 第二部分：200家清单 =====
L.append("\n---\n\n## 二、200家达标清单（按综合分降序）\n")
for i, e in enumerate(rows, 1):
    s = e["serial"]
    nm = e.get("name_cn") or e.get("name") or s
    rv = e.get("research_value", 0)
    l1s = "/".join(e.get("tag_l1") or []) or "—"
    l2s = "/".join(e.get("tag_l2") or []) or "—"
    stage = e.get("stage") or "—"
    payor = e.get("payor_model") or "—"
    sig = e.get("signal_strength"); inf = e.get("info_score"); dif = e.get("diff_score"); cop = e.get("copy_score")
    rec = e.get("recommend") or ""
    desc = e.get("desc_cn") or ""
    sil = e.get("silver_reason") or ""
    L.append(f"### {i}. {s} {nm}  ·  rv={rv}  ·  {l1s}/{l2s}")
    L.append(f"- **推荐理由**：{rec}")
    L.append(f"- **简介**：{desc}")
    L.append(f"- **银发判定**：{sil}")
    L.append(f"- **支付方**：{payor}  ·  **阶段**：{stage}  ·  **四维**：信号{sig}/信息{inf}/差异{dif}/可复制{cop}")
    L.append("")

open(OUT, "w", encoding="utf-8").write("\n".join(L))
print("已生成", OUT, "共", len(rows), "家；字数≈", sum(len(x) for x in L))
