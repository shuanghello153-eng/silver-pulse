fails = {}
r10_others = list(RECS.values())
for serial, rec in RECS.items():
    e = dict(by_serial[serial])
    e["recommend"] = rec
    # 逐条门禁（others=None 按团队要求，skip R6/R7/R8）
    iss = C.validate(e, others=None, skip={"R6", "R7", "R8"})
    # 额外的 R10 跨企业雷同自查（本批次内）
    r10 = C.validate(e, others=[v for v in r10_others if v != rec], skip={"R6", "R7", "R8", "R10"} if False else {"R6", "R7", "R8"})
    # 上面已经含 R10(others=None 时跳过)，这里单独跑跨企业
    iss_r10 = C.validate(e, others=r10_others, skip={"R6", "R7", "R8", "R5", "R-name", "R-redundancy", "R-integrity", "R-noabs", "R-jargon", "R2", "R3"})
    all_iss = list(iss)
    if iss_r10:
        # 仅当真雷同才追加
        for x in iss_r10:
            if x.startswith("R10"):
                all_iss.append(x)
    if all_iss:
        fails[serial] = all_iss
    else:
        results[serial] = rec
        # 写文件
        outp = os.path.join(OUT, f"draft_{serial}.json")
        json.dump({"serial": serial, "recommend": rec}, open(outp, "w", encoding="utf-8"), ensure_ascii=False, indent=2)

