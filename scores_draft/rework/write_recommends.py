def main():
    import json as _json, os as _os
    import check_single as C
    SRC = 'batches_full/batch_patch_gap.json'
    OUT = 'drafts_v4'
    _os.makedirs(OUT, exist_ok=True)
    d = _json.load(open(SRC, encoding='utf-8'))
    by = {x['serial']: x for x in d}
    fails = []
    written = 0
    for serial, rec in RECS.items():
        if serial not in by:
            print('!! 缺失源数据', serial); continue
        e = dict(by[serial]); e['recommend'] = rec
        fix = FIXES.get(serial)
        if fix:
            for k, v in fix.items():
                if v: e[k] = v
        errs = C.validate(e, skip={'R10'})
        out = {'serial': serial, 'recommend': rec}
        if fix: out.update({k: v for k, v in fix.items() if v})
        _json.dump(out, open(_os.path.join(OUT, f'draft_{serial}.json'), 'w', encoding='utf-8'), ensure_ascii=False, indent=2)
        written += 1
        if errs: fails.append((serial, errs))
    print(f'写入 {written} 家；通过 {len(RECS)-len(fails)} 家；失败 {len(fails)} 家')
    for s, errs in fails: print(' FAIL', s, errs)
    return fails

if __name__ == '__main__':
    main()
