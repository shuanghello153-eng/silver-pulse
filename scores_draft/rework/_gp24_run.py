recs = json.load(open(SRC, encoding="utf-8"))
n_total = len(recs)
n_pass = 0
n_fail = 0
fails = []
written = []
for r in recs:
    serial = r["serial"]
    txt = RECOMMEND.get(serial)
    if txt is None:
        fails.append((serial, "NO_RECOMMEND"))
        n_fail += 1
        continue
    # build full ctx from source record + recommend (as validator requires)
    ctx = dict(r)
    ctx["recommend"] = txt
    issues = C.validate(ctx, others=None, skip={"R6", "R7", "R8"})
    if issues:
        fails.append((serial, issues))
        n_fail += 1
        print(f"FAIL {serial}: {issues}")
    else:
        n_pass += 1
        out = {"serial": serial, "recommend": txt}
        with open(os.path.join(OUTDIR, f"draft_{serial}.json"), "w", encoding="utf-8") as f:
            json.dump(out, f, ensure_ascii=False, indent=2)
        written.append(serial)
        print(f"PASS {serial}")

print(f"\n=== SUMMARY ===")
print(f"total={n_total} pass={n_pass} fail={n_fail}")
print("written:", written)
if fails:
    print("fails:", fails)
