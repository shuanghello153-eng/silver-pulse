data = json.load(open(BATCH, encoding="utf-8"))
os.makedirs(OUTDIR, exist_ok=True)

passed, written, failed = 0, 0, []
for e in data:
    serial = e.get("serial")
    if serial not in recs:
        failed.append((serial, "missing recommend"))
        continue
    e2 = dict(e)
    e2["recommend"] = recs[serial]
    iss = C.validate({**e2}, others=None, skip={"R6", "R7", "R8"})
    if iss:
        failed.append((serial, iss))
        continue
    passed += 1
    out = {"serial": serial, "recommend": recs[serial]}
    with open(os.path.join(OUTDIR, f"draft_{serial}.json"), "w", encoding="utf-8") as f:
        json.dump(out, f, ensure_ascii=False, indent=2)
    written += 1

print(f"batch total={len(data)} passed={passed} written={written} failed={len(failed)}")
for s, iss in failed:
    print(f"  FAIL {s}: {iss}")
