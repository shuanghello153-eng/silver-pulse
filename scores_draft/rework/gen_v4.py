    if not isinstance(v,str): return v
    if "政府买单" in v: return "B端机构采购+政府付费"
    if v.strip() in ("个人自费/家庭自费",): return "个人自费"
    if "部分政府补贴" in v: return "个人自费+政府补贴"
    if v.strip()=="商业保险": return "政府医保/商业保险支付"
    if "雇主全额付费" in v: return "B端机构采购"
    if "(硬件)" in v: return "B端机构采购+个人自费"
    if "Medicare" in v or "Medicaid" in v: return "政府医保/商保支付"
    return v

