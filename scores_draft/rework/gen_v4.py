        for j in BANNED_JARGON:
            if j in rec:
                errors.append("%s recommend 含禁词 %s"%(serial,j))
        for t in TEMPLATE_BAD:
            if t in rec:
                errors.append("%s recommend 含模板/绝对化: %s"%(serial,t))
        has_num = bool(re.search(r"\d",rec))
        tags=c.get("tag_l1",[])+c.get("tag_l2",[])
        has_tag = any(t in rec for t in tags)
        if not (has_num or has_tag):
            errors.append("%s recommend 缺数字且缺标签词"%serial)
        dc = desc_override.get(serial, c.get("desc_cn",""))
        if cn_len(dc)<80:
            errors.append("%s desc_cn 长度=%d (<80)"%(serial,cn_len(dc)))
        if dc.startswith("是一家") or dc.startswith("致力于") or dc.startswith("专注于"):
            errors.append("%s desc_cn 开头违规"%serial)
        sr = silver_override.get(serial, c.get("silver_reason",""))
        if cn_len(sr)<30:
            errors.append("%s silver_reason 长度=%d (<30)"%(serial,cn_len(sr)))
        pm = normalize_payor(c.get("payor_model"))
        out={"serial":serial,"recommend":rec,"desc_cn":dc,"silver_reason":sr,"payor_model":pm}
        with open(os.path.join(OUT,"draft_%s.json"%serial.replace("#","")),"w",encoding="utf-8") as f:
            json.dump(out,f,ensure_ascii=False,indent=2)
        written+=1

