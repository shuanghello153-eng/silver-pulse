def ctx_for(serial):
    """读取已有 draft 以保留 silver_reason/payor_model 等附加字段。"""
    fp = os.path.join(OUT, f"draft_{serial}.json")
    if os.path.exists(fp):
        try:
            return json.load(open(fp, encoding="utf-8"))
        except Exception:
            return {}
    return {}

written = []
for e in batch:
    serial = e["serial"]
    recommend = RECS.get(serial) or KEEP_V5.get(serial)
    if recommend is None:
        print("!! 缺少推荐理由:", serial)
        continue
    info, diff, copy = SCORES[serial]
    old = ctx_for(serial)
    d = {
        "serial": serial,
        "recommend": recommend,
        "info": info,
        "diff": diff,
        "copy": copy,
        "desc_cn": e.get("desc_cn"),
        "highlights": e.get("highlights"),
        "stage": e.get("stage"),
    }
    # 保留可能由其他流程写入的附加字段
    for k in ("silver_reason", "payor_model"):
        if k in old and old[k]:
            d[k] = old[k]
    fp = os.path.join(OUT, f"draft_{serial}.json")
    json.dump(d, open(fp, "w", encoding="utf-8"), ensure_ascii=False, indent=2)
    written.append(serial)

print(f"已写 {len(written)} 个 draft")

