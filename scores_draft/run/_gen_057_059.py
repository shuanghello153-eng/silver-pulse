def build(batch_no, items):
    enterprises = []
    tag_review = []
    nonsilver = []
    for it in items:
        r = rv(it["info"], it["diff"], it["copy"])
        enterprises.append({
            "serial": it["serial"],
            "signal_strength": SIGNAL,
            "info_score": it["info"],
            "diff_score": it["diff"],
            "copy_score": it["copy"],
            "research_value": r,
            "recommend": {
                "rec_v1": it["v1"], "rec_v2": it["v2"], "rec_v3": it["v3"],
                "info_score": it["info"], "diff_score": it["diff"],
                "copy_score": it["copy"], "signal_strength": SIGNAL,
                "research_value": r,
            },
            "payor_model": it["payor"],
            "business_tags_role": it["role"],
            "desc_cn": it["desc_cn"],
            "founded": it["founded"],
            "stage": it["stage"],
            "events": it["events"],
            "highlights": it["highlights"],
            "update_time": "2026-07-17",
            "silver_verdict": it["verdict"],
            "silver_reason": it["reason"],
        })
        tag_review.append({
            "serial": it["serial"],
            "name": it["name"],
            "intro": it["tag_intro"],
            "old_tags": {
                "tag_l1": it["old_l1"],
                "tag_l2": it["old_l2"],
                "business_tags": it["old_bt"],
            },
            "suggested": it["suggested"],
        })
        if it["verdict"] in ("非银发", "泛医疗擦边"):
            nonsilver.append({
                "serial": it["serial"],
                "name": it["name"],
                "verdict": it["verdict"],
                "reason": it["reason"],
            })
    return {
        "batch": batch_no,
        "enterprises": enterprises,
        "tag_review": tag_review,
        "nonsilver": nonsilver,
    }

