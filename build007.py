def bigrams(s):
    s = re.sub(r"\s+", "", s)
    return set(s[i:i+2] for i in range(len(s)-1))

overlaps = []
for d in data:
    name = d["name"]
    desc = re.sub(r"\s+", "", d["description"])
    rec = re.sub(r"\s+", "", new_rec[name])
    db = bigrams(desc)
    rb = bigrams(rec)
    if not rb:
        ov = 0.0
    else:
        ov = len(db & rb) / len(rb)
    overlaps.append(ov)

avg = sum(overlaps)/len(overlaps)
print("avg bigram overlap (new rec vs description): %.3f" % avg)
print("max overlap:", "%.3f" % max(overlaps), "at", inp_names[overlaps.index(max(overlaps))])
print("count >0.30:", sum(1 for o in overlaps if o > 0.30))
