def bigrams(s):
    # keep only Chinese chars for bigram overlap
    s = re.sub(r'[^一-鿿]', '', s)
    return set(s[i:i+2] for i in range(len(s)-1))

counts = {}
overlaps = []  # proportion of recommend bigrams present in description
jaccards = []
out = {}
missing = []
for rec in data:
    name = rec["name"]
    desc = rec["description"]
    if name not in new_rec:
        missing.append(name)
        continue
    nr = new_rec[name]
    db = bigrams(desc)
    nb = bigrams(nr)
    if not nb:
        inter = 0
        prop = 0
        jac = 0
    else:
        inter = len(nb & db)
        prop = inter / len(nb)
        union = len(nb | db)
        jac = inter / union if union else 0
    overlaps.append(prop)
    jaccards.append(jac)
    out[name] = nr
    # rough char count
    counts[name] = len(nr)

with open(OUT, "w", encoding="utf-8") as f:
    json.dump(out, f, ensure_ascii=False, indent=2)

n = len(overlaps)
avg_prop = sum(overlaps)/n
avg_jac = sum(jaccards)/n
lens = list(counts.values())
