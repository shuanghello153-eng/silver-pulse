# bigram overlap
def bigrams(s):
    s = re.sub(r"\s+", "", s)
    return set(s[i:i+2] for i in range(len(s)-1))

def overlap(desc, rec):
    bd, br = bigrams(desc), bigrams(rec)
    if not br:
        return 0.0
    inter = len(bd & br)
    # metric1: intersection / recommend bigrams
    m1 = inter / len(br)
    # metric2: jaccard
    m2 = inter / len(bd | br) if (bd | br) else 0.0
    return m1, m2

sum1 = sum2 = 0.0
cnt = 0
high = []
name2desc = {d["name"]: d["description"] for d in data}
for n in names:
    d = name2desc[n]
    m1, m2 = overlap(d, new[n])
    sum1 += m1; sum2 += m2; cnt += 1
    if m1 > 0.30 or m2 > 0.20:
        high.append((n, round(m1,3), round(m2,3)))

print("avg overlap(inter/rec):", round(sum1/cnt,4))
print("avg overlap(jaccard):", round(sum2/cnt,4))
print("high overlap:", high)

