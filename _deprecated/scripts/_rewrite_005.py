def bigrams(s):
    s = re.sub(r'\s+', '', s)
    return set(s[i:i+2] for i in range(len(s)-1))

def overlap(a, b):
    A, B = bigrams(a), bigrams(b)
    if not A: return 0.0
    return len(A & B) / len(A)

