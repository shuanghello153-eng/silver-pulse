def bigrams(t):
    t = re.sub(r"\s+", "", t)
    return set(t[i:i+2] for i in range(len(t)-1)) if len(t) > 1 else set()

def overlap(desc, reco):
    if not desc or not reco: return 0.0
    d = bigrams(desc); r = bigrams(reco)
    if not d: return 0.0
    return len(d & r) / len(d)

