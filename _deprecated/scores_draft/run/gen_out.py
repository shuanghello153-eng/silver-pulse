def build(batch_no):
    path = os.path.join(INBOX, f"batch_{batch_no:03d}.json")
    with open(path, encoding="utf-8") as f:
        data = json.load(f)
    enterprises = []
    tag_review = []
    nonsilver = []
    for ent in data["enterprises"]:
        s = ent["serial"]
        ov = OV[s]
        sig = ent["signal_strength"]
        info = ov["info"]; diff = ov["diff"]; copy = ov["copy"]
        rv = round((sig*0.3 + info*0.3 + diff*0.2 + copy*0.2)*10, 1)
        out_ent = {
            "serial": s,
            "signal_strength": sig,
            "info_score": info,
            "diff_score": diff,
            "copy_score": copy,
            "research_value": rv,
            "recommend": {
                "rec_v1": ov["rec_v1"],
                "rec_v2": ov["rec_v2"],
                "rec_v3": ov["rec_v3"],
                "info_score": info,
                "diff_score": diff,
                "copy_score": copy,
                "signal_strength": sig,
                "research_value": rv,
            },
            "payor_model": ov["payor"],
            "business_tags_role": ov["role"],
            "desc_cn": ov["desc_cn"],
            "founded": ov["founded"],
            "stage": ov["stage"],
            "events": ov["events"],
            "highlights": ov["highlights"],
            "update_time": "2026-07-17",
            "silver_verdict": ov["verdict"],
            "silver_reason": ov["sreason"],
        }
        enterprises.append(out_ent)
        # tag review
        old_tags = {
            "tag_l1": ent.get("tag_l1", []),
            "tag_l2": ent.get("tag_l2", []),
            "business_tags": ent.get("business_tags", {}),
        }
        tag_review.append({
            "serial": s,
            "name": ent["name"],
            "intro": ov["tag_intro"],
            "old_tags": old_tags,
            "suggested": ov["tag_suggested"],
        })
        if ov["verdict"] in ("非银发", "泛医疗擦边"):
            nonsilver.append({
                "serial": s,
                "name": ent["name"],
                "verdict": ov["verdict"],
                "reason": ov["sreason"],
            })
    out = {
        "batch": batch_no,
        "enterprises": enterprises,
        "tag_review": tag_review,
        "nonsilver": nonsilver,
    }
    opath = os.path.join(OUT, f"batch_{batch_no:03d}_out.json")
    with open(opath, "w", encoding="utf-8") as f:
        json.dump(out, f, ensure_ascii=False, indent=2)
    return out

