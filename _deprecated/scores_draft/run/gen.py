def build(batch, data):
    enterprises = []
    tag_review = []
    nonsilver = []
    for e in data:
        rvalue = rv(e["signal"], e["info"], e["diff"], e["copy"])
        enterprises.append({
            "serial": e["serial"],
            "signal_strength": e["signal"],
            "info_score": e["info"],
            "diff_score": e["diff"],
            "copy_score": e["copy"],
            "research_value": rvalue,
            "recommend": {
                "rec_v1": e["r1"],
                "rec_v2": e["r2"],
                "rec_v3": e["r3"],
                "info_score": e["info"],
                "diff_score": e["diff"],
                "copy_score": e["copy"],
                "signal_strength": e["signal"],
                "research_value": rvalue,
            },
            "payor_model": e["payor"],
            "business_tags_role": e["role"],
            "desc_cn": e["desc_cn"],
            "founded": e["founded"],
            "stage": e["stage"],
            "events": e["events"],
            "highlights": e["highlights"],
            "update_time": "2026-07-17",
            "silver_verdict": e["verdict"],
            "silver_reason": e["reason"],
        })
        tag_review.append({
            "serial": e["serial"],
            "name": e["name"],
            "intro": e["intro"],
            "old_tags": {
                "tag_l1": e["old_l1"],
                "tag_l2": e["old_l2"],
                "business_tags": e["old_bt"],
            },
            "suggested": e["suggested"],
        })
        if e["verdict"] in ("非银发", "泛医疗擦边"):
            nonsilver.append({
                "serial": e["serial"],
                "name": e["name"],
                "verdict": e["verdict"],
                "reason": e["reason"],
            })
    return {
        "batch": batch,
        "enterprises": enterprises,
        "tag_review": tag_review,
        "nonsilver": nonsilver,
    }

